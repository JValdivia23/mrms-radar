"""Bundle public-domain Natural Earth v5.1.2 data; no runtime data service.

Run: python tools/build_natural_earth.py [--source-dir DIRECTORY]
The optional directory contains countries.geojson, states.geojson, places.geojson.
"""
import argparse
import json
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/"
SOURCES = {
    "countries": "ne_110m_admin_0_countries.geojson",
    "states": "ne_50m_admin_1_states_provinces.geojson",
    "places": "ne_10m_populated_places_simple.geojson",
}


def compact_coordinates(value):
    if isinstance(value, list):
        return [compact_coordinates(item) for item in value]
    return round(value, 4) if isinstance(value, float) else value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path)
    args = parser.parse_args()
    bundle = {}
    for key, filename in SOURCES.items():
        if args.source_dir:
            raw = (args.source_dir / f"{key}.geojson").read_text()
        else:
            with urlopen(BASE + filename, timeout=60) as response:
                raw = response.read()
        features = json.loads(raw)["features"]
        if key == "places":
            bundle[key] = sorted([
                [f["properties"]["name"], *compact_coordinates(f["geometry"]["coordinates"]),
                 f["properties"]["min_zoom"], f["properties"]["pop_max"]]
                for f in features
            ], key=lambda p: -p[4])
        else:
            bundle[key] = {"type": "FeatureCollection", "features": [
                {"type": "Feature", "properties": {},
                 "geometry": {"type": f["geometry"]["type"],
                              "coordinates": compact_coordinates(f["geometry"]["coordinates"])}}
                for f in features
            ]}
    output = ("// Natural Earth v5.1.2; public domain. Generated by tools/build_natural_earth.py.\n"
              "// Sources: " + BASE + "\n"
              "window.MRMSNaturalEarthData=" + json.dumps(bundle, ensure_ascii=True, separators=(",", ":")) + ";\n")
    (ROOT / "static" / "natural-earth-data.js").write_text(output)
    print(f"Bundled {len(output):,} bytes of Natural Earth geography")


if __name__ == "__main__":
    main()
